    var _lang = localStorage.getItem('lang') || 'fr';

    function t(key, vars) {
      var s = (TRANSLATIONS[_lang] || TRANSLATIONS['fr'])[key] || key;
      if (vars) Object.keys(vars).forEach(function (k) { s = s.replace('{' + k + '}', vars[k]); });
      return s;
    }

    // Board-type translation with fallback to the English value from board_types.json.
    function tbt(type, field, fallback) {
      var key = 'bt.' + type + '.' + field;
      var dict = TRANSLATIONS[_lang] || TRANSLATIONS['fr'];
      return dict[key] || fallback;
    }

    function setLang(lang) {
      _lang = lang;
      localStorage.setItem('lang', lang);
      applyLang();
    }

    function applyLang() {
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        // Skip the cfg-filename div — its text is managed by onCfgFileSelect
        if (el.id === 'cfg-filename') return;
        // Skip prm-system-fields — it contains dynamically generated HTML
        if (el.id === 'prm-system-fields') return;
        el.textContent = t(el.getAttribute('data-i18n'));
      });
      document.getElementById('lang-fr').classList.toggle('active', _lang === 'fr');
      document.getElementById('lang-en').classList.toggle('active', _lang === 'en');
    }
